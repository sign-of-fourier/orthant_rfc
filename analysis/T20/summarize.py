"""T20 summary: python analysis/T20/summarize.py [--boot 2000]

Reads out/results.json (run.py assemble). The grid is asymmetric by design (user, 2026-10-19, "binary
search"): HB-MNL + RFC-S at all 11 N, MVP at N = 50, 100, 200 only. So:
  - mean decision error by N per method, 95% bootstrap CI over replicates; RFC-S - MVP paired by dataset
    where both ran;
  - RFC-S curve err(N) = a + b N^-c (bounded least squares on cell means, a, b >= 0, 0.05 <= c <= 3), with
    bootstrap CIs (replicates resampled within N);
  - (a) RFC-S floor a minus MVP's mean at each MVP N;
  - (b) equivalent sample size at target e = MVP's mean error at N_MVP: N_RFC-S(e) = (b / (e - a))^(1/c),
    ratio N_RFC-S / N_MVP, "no crossing" when e <= a; plus a model-free bound: the smallest grid N at which
    RFC-S's mean is <= e (none up to 1,500 -> ratio > 1,500 / N_MVP). MVP's error is a target here, so its
    sampling noise enters the bootstrap (independent draws for the two methods' cells).
Metrics: cost regret % (primary, T5's regret metric) and flips per replicate (price + ext + cost, 0-3).
Writes out/RESULTS.md, out/err_vs_N_<metric>.png and out/multiplier_<metric>.png.
"""
import argparse
import json
from pathlib import Path

import numpy as np
from scipy.optimize import curve_fit

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
TRUTHS = ("G1", "G2", "G0")
METHODS = (("mvp", "MVP"), ("rfc_s", "HB-MNL + RFC-S"))
FLIPS = ("price_flip", "ext_flip_at_placeholder_h", "cost_flip")
METRICS = {"cost_regret": "cost regret %", "flips": "flips per replicate"}
LO, HI = [0.0, 0.0, 0.05], [np.inf, np.inf, 3.0]
MVP_NS = (50, 100, 200)  # the design; the G1 N = 1,500 smoke fit (1 replicate) is not a cell


def err(x, metric):
    return float(sum(bool(x[k]) for k in FLIPS)) if metric == "flips" else float(x["cost_regret_pct"])


def law(n, a, b, c):
    return a + b * np.asarray(n, float) ** (-c)


def fit_law(ns, means):
    if np.allclose(means, means[0]):
        return np.array([means[0], 0.0, 1.0])
    best = None
    for c0 in (0.3, 0.7, 1.5):
        p0 = [max(means.min(), 0.0), max(means.max() - means.min(), 1e-6) * ns.min() ** c0, c0]
        try:
            p, _ = curve_fit(law, ns, means, p0=p0, bounds=(LO, HI), maxfev=20000)
        except (RuntimeError, ValueError):
            continue
        sse = np.sum((law(ns, *p) - means) ** 2)
        if best is None or sse < best[0]:
            best = (sse, p)
    return None if best is None else best[1]


def n_at(p, e):
    a, b, c = p
    return np.inf if (e <= a or b <= 0) else (b / (e - a)) ** (1 / c)


def cells(recs, truth, m, metric):
    """{N: {rep: error}} for one method."""
    out = {}
    for r in recs:
        if r["truth"] == truth and r[m] is not None and (m != "mvp" or r["N"] in MVP_NS):
            out.setdefault(r["N"], {})[r["rep"]] = err(r[m], metric)
    return dict(sorted(out.items()))


def pct(x, q=(2.5, 97.5)):
    x = np.asarray(x, float)
    return np.percentile(x, q, method="nearest") if len(x) else (np.nan, np.nan)


def f(x, d=2, sign=False):
    if np.isinf(x):
        return "∞" if x > 0 else "−∞"
    return f"{x:+.{d}f}" if sign else f"{x:.{d}f}"


def main():
    global OUT
    ap = argparse.ArgumentParser()
    ap.add_argument("--boot", type=int, default=2000)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    if a.out:
        OUT = Path(a.out)
    recs = json.loads((OUT / "results.json").read_text())
    rng = np.random.default_rng(20261019)
    L = ["# T20 results: sample-size curves", "",
         f"Generated by `python analysis/T20/summarize.py` from out/results.json. CIs are 95% bootstrap over "
         f"replicates ({a.boot} draws). HB-MNL + RFC-S ran at all 11 N; MVP at N = 50, 100, 200 (user's "
         f"binary-search cut, 2026-10-19).", "",
         "## Fits and time", "",
         "| truth | N | R MVP | MVP not converged | MVP fit s, median (T4) | R RFC-S | HB s, median (1 CPU) | "
         "RFC-S tune s, median | RFC-S tuning at a bound |", "|---|---|---|---|---|---|---|---|---|"]
    md = lambda v: f"{np.median(v):.0f}" if v else "—"  # noqa: E731
    for truth in TRUTHS:
        for n in sorted({r["N"] for r in recs if r["truth"] == truth}):
            rs = [r for r in recs if r["truth"] == truth and r["N"] == n]
            mv = [r["mvp"] for r in rs if r["mvp"] and n in MVP_NS]
            rf = [r["rfc_s"] for r in rs if r["rfc_s"]]
            L.append(f"| {truth} | {n} | {len(mv)} | {sum(not x['converged'] for x in mv) if mv else '—'} | "
                     f"{md([x['seconds']['fit'] for x in mv])} | {len(rf)} | {md([x['seconds']['hb'] for x in rf])} | "
                     f"{md([x['seconds']['tune'] for x in rf])} | {sum(bool(x['flags']) for x in rf)} |")
    L.append("")

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    for metric, mlab in METRICS.items():
        L += [f"## {mlab}", ""]
        fig, axes = plt.subplots(1, 3, figsize=(15, 4), sharey=True)
        fig2, axes2 = plt.subplots(1, 3, figsize=(15, 4), sharey=True)
        for ax, ax2, truth in zip(axes, axes2, TRUTHS):
            C = {m: cells(recs, truth, m, metric) for m, _ in METHODS}
            if not C["rfc_s"] or not C["mvp"]:
                continue
            ns_r, ns_m = np.array(list(C["rfc_s"])), np.array(list(C["mvp"]))
            both = {n: sorted(set(C["mvp"][n]) & set(C["rfc_s"].get(n, {}))) for n in ns_m}
            both = {n: k for n, k in both.items() if k}
            mean = {m: {n: np.mean(list(C[m][n].values())) for n in C[m]} for m, _ in METHODS}
            # bootstrap: per method and N, resample that cell's replicates; paired difference where both ran
            bm = {m: {n: np.empty(a.boot) for n in C[m]} for m, _ in METHODS}
            bd = {n: np.empty(a.boot) for n in both}
            arr = {m: {n: np.array(list(C[m][n].values())) for n in C[m]} for m, _ in METHODS}
            dif = {n: np.array([C["rfc_s"][n][k] - C["mvp"][n][k] for k in both[n]]) for n in both}
            for i in range(a.boot):
                for m, _ in METHODS:
                    for n, v in arr[m].items():
                        bm[m][n][i] = v[rng.integers(0, len(v), len(v))].mean()
                for n, v in dif.items():
                    bd[n][i] = v[rng.integers(0, len(v), len(v))].mean()
            L += [f"### {truth}" + (" (logit control)" if truth == "G0" else ""), "",
                  "| N | MVP mean [95% CI] | RFC-S mean [95% CI] | RFC-S − MVP, paired [95% CI] |", "|---|---|---|---|"]
            for n in sorted(set(ns_r) | set(ns_m)):
                cell = lambda m: (f"{mean[m][n]:.2f} [{pct(bm[m][n])[0]:.2f}, {pct(bm[m][n])[1]:.2f}]"  # noqa: E731
                                  if n in C[m] else "—")
                cd = (f"{dif[n].mean():+.2f} [{pct(bd[n])[0]:+.2f}, {pct(bd[n])[1]:+.2f}]" if n in both else "—")
                L.append(f"| {n} | {cell('mvp')} | {cell('rfc_s')} | {cd} |")
            # RFC-S curve and the multiplier at MVP's N
            pr = fit_law(ns_r, np.array([mean["rfc_s"][n] for n in ns_r]))
            bp = [fit_law(ns_r, np.array([bm["rfc_s"][n][i] for n in ns_r])) for i in range(a.boot)]
            ok = np.array([p for p in bp if p is not None])
            L += ["", "RFC-S curve err(N) = a + b·N^(−c):", "",
                  "| a (floor) [95% CI] | b [95% CI] | c [95% CI] | bootstrap fits failed |", "|---|---|---|---|",
                  "| " + " | ".join(f"{pr[k]:.3g} [{pct(ok[:, k])[0]:.3g}, {pct(ok[:, k])[1]:.3g}]" for k in range(3))
                  + f" | {sum(p is None for p in bp)} of {a.boot} |", "",
                  "| N_MVP | target e = MVP mean | RFC-S floor a − e [95% CI] | N_RFC-S(e), fitted | ratio [95% CI] | "
                  "P(no crossing) | model-free: smallest RFC-S grid N with mean ≤ e |", "|---|---|---|---|---|---|---|"]
            rat = []
            for n in ns_m:
                e = mean["mvp"][n]
                idx = [i for i, p in enumerate(bp) if p is not None]
                fa = np.array([bp[i][0] - bm["mvp"][n][i] for i in idx])
                br = np.array([n_at(bp[i], bm["mvp"][n][i]) / n for i in idx])
                nr = n_at(pr, e)
                lo, hi = pct(br)
                hit = [k for k in ns_r if mean["rfc_s"][k] <= e]
                mf = (f"{min(hit)} (ratio ≈ {min(hit) / n:.1f})" if hit
                      else f"none ≤ {ns_r.max()} (ratio > {ns_r.max() / n:.1f})")
                extrap = " (extrap.)" if np.isfinite(nr) and nr > ns_r.max() else ""
                L.append(f"| {n} | {e:.2f} | {f(pr[0] - e, sign=True)} [{f(pct(fa)[0], sign=True)}, "
                         f"{f(pct(fa)[1], sign=True)}] | {f(nr, 0)}{extrap} | {f(nr / n)} [{f(lo)}, {f(hi)}] | "
                         f"{np.mean(np.isinf(br)):.2f} | {mf} |")
                rat.append((e, nr / n, lo, hi, n))
            L.append("")
            # plots
            for m, lab in METHODS:
                ns = np.array(list(C[m]))
                mm = np.array([mean[m][n] for n in ns])
                q = np.array([pct(bm[m][n]) for n in ns])
                l = ax.errorbar(ns, mm, yerr=[mm - q[:, 0], q[:, 1] - mm], fmt="o", capsize=3, label=lab)
                if m == "rfc_s":
                    xx = np.geomspace(50, 1500, 200)
                    ax.plot(xx, law(xx, *pr), "--", color=l[0].get_color())
                    ax.axhline(pr[0], color=l[0].get_color(), lw=0.6, ls=":")
            ax.set_xscale("log")
            ax.set_title(truth + (" (logit control)" if truth == "G0" else ""))
            ax.set_xlabel("N respondents")
            ax.legend()
            for e, r, lo, hi, n in rat:
                if np.isfinite(r):
                    ax2.errorbar([e], [r], yerr=[[max(r - lo, 0)], [max(hi - r, 0) if np.isfinite(hi) else 0]],
                                 fmt="o", capsize=3, color="C0")
                    ax2.annotate(f"N_MVP={n}", (e, r), textcoords="offset points", xytext=(5, 5), fontsize=8)
                else:
                    ax2.axvline(e, color="0.85", lw=4)
                    ax2.annotate(f"N_MVP={n}: no crossing", (e, 1.1), rotation=90, fontsize=8, va="bottom")
            ax2.axhline(1, color="0.5", lw=0.8)
            ax2.axhline(2, color="r", lw=0.8, ls=":")
            ax2.set_yscale("log")
            ax2.set_title(truth)
            ax2.set_xlabel(f"target error = MVP's mean ({mlab})")
        axes[0].set_ylabel(mlab)
        axes2[0].set_ylabel("N_RFC-S / N_MVP")
        for fg, name in ((fig, "err_vs_N"), (fig2, "multiplier")):
            fg.tight_layout()
            fg.savefig(OUT / f"{name}_{metric}.png", dpi=120)
        plt.close("all")
    (OUT / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
