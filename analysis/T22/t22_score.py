"""T22 scoring on the held-out respondents (all 9 tasks each), population predictive probabilities.

Metrics, per training subset and model (MNL, NL, HB-MNL, RFC-S, MVP):
  ll      mean log-likelihood per choice
  bins    share MAE (pts) over 9 cells x 3 alternatives: tertiles of SM cost - train cost x tertiles of car time -
          train time (cut on the holdout tasks), i.e. calibration where the substitution pattern matters
  policy  SM cost x 1.2 on every holdout task: share changes and the share of SM's loss that goes to train
          (no ground truth; reported as each model's answer)
Bootstrap over holdout respondents (B = 1,000), paired differences against MVP. Writes out/scores.json and
out/report.md.
"""
import json

import numpy as np

import t22

B_BOOT = 1000
MODELS = ("MNL", "NL", "HB-MNL", "RFC-S", "MVP")


def predict(tag, Xh):
    loc = json.loads((t22.OUT / f"local_{tag}.json").read_text())
    m = Xh.shape[0]
    Xf = Xh.reshape(-1, 3, t22.P)
    out = {"MNL": np.exp(t22.log_softmax(Xf @ np.array(loc["mnl"]), -1)),
           "NL": np.exp(t22.nl_logp(Xf, np.array(loc["nl"]), loc["nl_lambda"]))}
    R = t22.RFC(np.load(t22.OUT / f"hb_{tag}.npy"), np.random.default_rng([t22.SEED, 1]))
    out["HB-MNL"] = R.probs(Xf, 0.0, 1.0)
    out["RFC-S"] = R.probs(Xf, loc["rfc"]["sigma_l"], loc["rfc"]["g"])
    mp = t22.OUT / f"mvp_{tag}.json"
    if mp.exists():
        out["MVP"] = t22.mvp_probs(Xf, np.array(json.loads(mp.read_text())["theta"]))
    return {k: v.reshape(m, 9, 3) for k, v in out.items()}


def summarize(x):
    x = np.asarray(x, float)
    return dict(pt=float(x[0]), lo=float(np.percentile(x[1:], 2.5)), hi=float(np.percentile(x[1:], 97.5)))


def main():
    X, y, ids = t22.load()
    tr, ho = t22.split(len(ids))
    Xh, yh = X[ho], y[ho]
    nh = len(ho)
    Xp = Xh.copy()
    Xp[:, :, 1, 3] *= t22.POLICY
    # bins on the holdout tasks
    dc = Xh[:, :, 1, 3] - Xh[:, :, 0, 3]
    dt = Xh[:, :, 2, 2] - Xh[:, :, 0, 2]
    cut = lambda v: np.digitize(v, np.quantile(v, [1 / 3, 2 / 3]))  # noqa: E731
    bin_ = cut(dc) * 3 + cut(dt)                                          # (nh, 9)
    onehot = np.eye(9)[bin_]                                              # (nh, 9, 9 bins)
    Y1 = np.eye(3)[yh]
    cnt_r = onehot.sum(1)                                                 # (nh, bins)
    obs_r = np.einsum("rtb,rta->rba", onehot, Y1)
    W = np.random.default_rng(t22.SEED).multinomial(nh, np.full(nh, 1 / nh), size=B_BOOT).astype(float)
    W = np.vstack([np.ones(nh), W])                                       # row 0 = the sample

    def wshare(arr_r):
        return np.einsum("wr,rba->wba", W, arr_r) / np.einsum("wr,rb->wb", W, cnt_r)[..., None]
    obs_b = wshare(obs_r)

    res = {}
    for tag in t22.subsets(tr):
        if not (t22.OUT / f"local_{tag}.json").exists():
            continue
        pr, pp = predict(tag, Xh), predict(tag, Xp)
        r = {"models": list(pr)}
        ll_r = {k: np.log(np.clip(np.take_along_axis(v, yh[..., None], 2)[..., 0], 1e-300, None)).sum(1)
                for k, v in pr.items()}
        ll = {k: (W @ v) / (W.sum(1) * 9) for k, v in ll_r.items()}
        mae = {k: np.abs(wshare(np.einsum("rtb,rta->rba", onehot, v)) - obs_b).mean((1, 2)) * 100 for k, v in pr.items()}
        r["ll"] = {k: summarize(v) for k, v in ll.items()}
        r["bins_mae_pts"] = {k: summarize(v) for k, v in mae.items()}
        if "MVP" in pr:
            r["ll_mvp_minus"] = {k: summarize(ll["MVP"] - ll[k]) for k in pr if k != "MVP"}
            r["bins_minus_mvp"] = {k: summarize(mae[k] - mae["MVP"]) for k in pr if k != "MVP"}
        pol = {}
        for k in pr:
            d = (pp[k] - pr[k]).mean((0, 1)) * 100
            pol[k] = dict(d_train=float(d[0]), d_sm=float(d[1]), d_car=float(d[2]), to_train=float(d[0] / -d[1]))
        r["policy"] = pol
        r["shares_pred"] = {k: (v.mean((0, 1)) * 100).tolist() for k, v in pr.items()}
        r["shares_obs"] = (Y1.mean((0, 1)) * 100).tolist()
        res[tag] = r
        print(tag, "ll", {k: round(v["pt"], 4) for k, v in r["ll"].items()}, flush=True)
    (t22.OUT / "scores.json").write_text(json.dumps(res, indent=1))
    report(res)


def fmt(c, k=3, sign=True):
    f = f"{{:{'+' if sign else ''}.{k}f}}"
    return f"{f.format(c['pt'])} [{f.format(c['lo'])}, {f.format(c['hi'])}]"


def report(res):
    L = ["# T22 · Swissmetro holdout scores (generated by t22_score.py)\n",
         "Held-out respondents, all 9 tasks, population predictive probabilities. Log-likelihood per choice "
         "(higher is better); share MAE in pts over 9 bins x 3 alternatives. Differences: positive = MVP better.\n",
         "## Log-likelihood per choice\n",
         "| train | " + " | ".join(MODELS) + " | MVP − MNL | MVP − NL | MVP − HB-MNL | MVP − RFC-S |",
         "|---|" + "---|" * (len(MODELS) + 4)]
    for tag, r in res.items():
        d = r.get("ll_mvp_minus", {})
        L.append(f"| {tag} | " + " | ".join(f"{r['ll'][k]['pt']:.4f}" if k in r["ll"] else "—" for k in MODELS) + " | "
                 + " | ".join(fmt(d[k]) if k in d else "—" for k in ("MNL", "NL", "HB-MNL", "RFC-S")) + " |")
    L += ["\n## Share MAE over 9 bins (pts)\n",
          "| train | " + " | ".join(MODELS) + " | MNL − MVP | NL − MVP | HB-MNL − MVP | RFC-S − MVP |",
          "|---|" + "---|" * (len(MODELS) + 4)]
    for tag, r in res.items():
        d = r.get("bins_minus_mvp", {})
        L.append(f"| {tag} | " + " | ".join(f"{r['bins_mae_pts'][k]['pt']:.2f}" if k in r["bins_mae_pts"] else "—"
                                            for k in MODELS) + " | "
                 + " | ".join(fmt(d[k], 2) if k in d else "—" for k in ("MNL", "NL", "HB-MNL", "RFC-S")) + " |")
    L += ["\n## Policy: SM cost x 1.2 (share change, pts; share of SM's loss going to train)\n",
          "| train | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    for tag, r in res.items():
        p = r["policy"]
        L.append(f"| {tag} | " + " | ".join(f"SM {p[k]['d_sm']:+.2f}, to train {100 * p[k]['to_train']:.0f}%"
                                            if k in p else "—" for k in MODELS) + " |")
    (t22.OUT / "report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
